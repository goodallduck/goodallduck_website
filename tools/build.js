// - writes each page's <head> SEO block (title, description, canonical, Open Graph, JSON-LD)
// - pre-renders work cards into [data-works] so crawlers that don't run JS (e.g. Naver) see them
// - regenerates sitemap.xml
// Run it after editing assets/js/works.js or the PAGES table below.
